using System.Collections.Immutable;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace FlickerVoid.Tools.Generators;

/// <summary>
/// Writes <c>FlowNodeTypes.Register(DataTypes)</c> into a game project, registering every class marked
/// <c>[FlowNodeType("name")]</c> as a flow node under its name, in name order; the project's module calls it once.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class FlowNodeTypesGenerator : IIncrementalGenerator
{
    private const string AttributeName = "FlickerVoid.Engine.Flow.Graphs.FlowNodeTypeAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<NodeType> types = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax,
            static (attributed, _) => Read(attributed));
        IncrementalValueProvider<(ImmutableArray<NodeType> Types, string? Assembly)> all =
            types.Collect().Combine(context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName));
        context.RegisterSourceOutput(all, static (output, found) => Write(output, found.Types, found.Assembly));
    }

    private static NodeType Read(GeneratorAttributeSyntaxContext attributed)
    {
        INamedTypeSymbol type = (INamedTypeSymbol)attributed.TargetSymbol;
        AttributeData attribute = attributed.Attributes[0];
        string name = attribute.ConstructorArguments.Length > 0 ? attribute.ConstructorArguments[0].Value as string ?? type.Name : type.Name;
        string fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return new NodeType(fullName, name);
    }

    private static void Write(SourceProductionContext output, ImmutableArray<NodeType> types, string? assembly)
    {
        string space = string.IsNullOrEmpty(assembly) ? "FlickerVoid.Generated" : assembly!;
        StringBuilder text = new();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine($"namespace {space};");
        text.AppendLine();
        text.AppendLine("/// <summary>Registers this project's flow node types, the classes marked [FlowNodeType].</summary>");
        text.AppendLine("internal static class FlowNodeTypes");
        text.AppendLine("{");
        text.AppendLine("    public static void Register(global::FlickerVoid.Engine.Runtime.Data.DataTypes data)");
        text.AppendLine("    {");
        foreach (NodeType type in types.OrderBy(static type => type.Name, System.StringComparer.Ordinal))
        {
            text.AppendLine($"        data.RegisterDerived<global::FlickerVoid.Engine.Flow.Graphs.FlowNode, {type.FullName}>(\"{type.Name}\");");
        }

        text.AppendLine("    }");
        text.AppendLine("}");
        output.AddSource("FlowNodeTypes.g.cs", SourceText.From(text.ToString(), Encoding.UTF8));
    }

    private readonly struct NodeType(string fullName, string name) : System.IEquatable<NodeType>
    {
        public string FullName { get; } = fullName;

        public string Name { get; } = name;

        public bool Equals(NodeType other) => FullName == other.FullName && Name == other.Name;

        public override bool Equals(object? obj) => obj is NodeType other && Equals(other);

        public override int GetHashCode() => (FullName.GetHashCode() * 31) + Name.GetHashCode();
    }
}
